//! Host-runnable source contract: Android-only commands are excluded from desktop
//! compilation, but must never regress to waiting on Binder from AndroidJavaBridge.
//! Also runnable without GTK/Android: `rustc --test --edition=2021 <this file>`.

const COMMANDS: &str = include_str!("../src/mobile_commands.rs");
const REGISTRATION: &str = include_str!("../src/lib.rs");
const NATIVE_PLUGIN: &str = include_str!("../src/android_backend_service.rs");
const DESKTOP_COMMANDS: &str = include_str!("../src/commands.rs");
const MOBILE_ACL: &str = include_str!("../permissions/autogenerated/commands/mobile-commands.toml");
const DEFAULT_PERMISSION: &str = include_str!("../permissions/default.toml");
const ANDROID_CAPABILITY: &str = include_str!("../capabilities/android.json");
const NATIVE_COMMANDS: &[&str] = &[
    "android_list_games",
    "android_launch_game",
    "android_game_stream_info",
    "android_shizuku_status",
    "android_request_shizuku_permission",
    "android_open_shizuku",
    "android_set_system_bars",
    "android_game_screenshot",
    "android_game_preview",
    "android_game_native_preview",
    "android_game_fullscreen",
    "android_game_resume_automation",
    "android_game_gesture",
];

fn command(name: &str) -> &'static str {
    let signature = format!("pub async fn {name}(");
    let offset = COMMANDS
        .find(&signature)
        .unwrap_or_else(|| panic!("{name} must remain async"));
    let source = &COMMANDS[offset..];
    let end = source.find("\n}\n").expect("command closing brace");
    &source[..end]
}

#[test]
fn explicit_automation_resume_keeps_the_owned_display_payload_and_json_response() {
    let bridge = command("android_game_resume_automation");
    assert!(bridge.contains("request: Value"));
    assert!(bridge.contains("Result<Value, String>"));
    assert!(bridge.contains("game_resume_automation(&app, request)"));
    assert!(NATIVE_PLUGIN.contains(".run_mobile_plugin(\"gameResumeAutomation\", request)"));
    assert!(DESKTOP_COMMANDS.contains("pub fn android_game_resume_automation(_request: serde_json::Value) -> Result<serde_json::Value, String>"));
    assert!(
        REGISTRATION
            .matches("android_game_resume_automation")
            .count()
            >= 3
    );
}

#[test]
fn native_queries_and_actions_wait_off_the_command_dispatch_thread() {
    for name in NATIVE_COMMANDS {
        let body = command(name);
        let worker = body
            .find("tauri::async_runtime::spawn_blocking(move ||")
            .unwrap_or_else(|| panic!("{name} needs a blocking worker"));
        let native = body
            .find("crate::android_backend_service::")
            .expect("native plugin call");
        assert!(
            worker < native,
            "{name} must not call the native plugin before dispatching its worker"
        );
        assert!(
            body.contains(".await"),
            "{name} must await worker completion asynchronously"
        );
        assert!(
            body.contains("worker failed:"),
            "{name} must propagate worker failures"
        );
    }
}

#[test]
fn command_registration_keeps_every_public_native_entry_point() {
    let handlers = REGISTRATION
        .split("generate_handler![")
        .nth(1)
        .expect("Tauri command registry");
    let handlers = handlers.split("])").next().unwrap();
    let entries: Vec<_> = handlers.split(',').map(str::trim).collect();
    for name in NATIVE_COMMANDS.iter().copied().chain([
        "updater_reset_backend_auth_and_restart",
        "backend_transport_start",
    ]) {
        assert!(
            entries.contains(&name),
            "{name} must remain registered under its existing name"
        );
    }
}

#[test]
fn registered_android_commands_are_reachable_through_the_mobile_acl() {
    let handlers = REGISTRATION
        .split("generate_handler![")
        .nth(1)
        .expect("Tauri command registry")
        .split("])")
        .next()
        .unwrap();
    let allowed = MOBILE_ACL
        .split("commands.allow = [")
        .nth(1)
        .expect("explicit mobile command allowlist")
        .split(']')
        .next()
        .unwrap();
    let allowed: Vec<_> = allowed
        .lines()
        .filter_map(|line| line.trim().strip_prefix('"')?.split('"').next())
        .collect();
    assert!(!allowed.contains(&"*"), "Keep mobile permissions explicit");
    for name in handlers
        .split(',')
        .map(str::trim)
        .filter(|name| name.starts_with("android_"))
    {
        assert!(
            allowed.contains(&name),
            "{name} is registered but unreachable from Android without its ACL permission"
        );
    }
    assert!(MOBILE_ACL.contains("identifier = \"allow-mobile-commands\""));
    assert!(DEFAULT_PERMISSION.contains("[default]"));
    assert!(DEFAULT_PERMISSION.contains("\"allow-mobile-commands\""));
    let permissions = ANDROID_CAPABILITY
        .split("\"permissions\": [")
        .nth(1)
        .expect("Android capability permissions")
        .split(']')
        .next()
        .unwrap();
    assert!(
        permissions
            .lines()
            .any(|line| line.trim().trim_end_matches(',') == "\"default\""),
        "Android's main webview must inherit the application default permission"
    );
}

#[test]
fn backend_service_startup_also_dispatches_native_waits_to_a_worker() {
    for name in [
        "updater_reset_backend_auth_and_restart",
        "backend_transport_start",
    ] {
        let body = command(name);
        let worker = body
            .find("tauri::async_runtime::spawn_blocking(move ||")
            .expect("native startup worker");
        let native = body
            .find("ensure_android_backend_service(&app)")
            .expect("native service startup");
        assert!(
            worker < native,
            "{name} must not wait for ensureStarted before its worker"
        );
        assert!(body.contains(".await"));
    }
    let reset = command("updater_reset_backend_auth_and_restart");
    assert!(reset.contains("\"restarted\": false"));
    assert!(reset.contains("\"restart_deferred\": true"));
}

#[test]
fn query_json_and_action_unit_return_shapes_are_unchanged() {
    for name in [
        "android_list_games",
        "android_game_stream_info",
        "android_shizuku_status",
    ] {
        let body = command(name);
        assert!(body
            .split('{')
            .next()
            .unwrap()
            .contains("Result<Value, String>"));
        assert!(
            body.contains("serde_json::to_value("),
            "{name} must preserve the JSON response"
        );
    }
    for name in [
        "android_launch_game",
        "android_request_shizuku_permission",
        "android_open_shizuku",
        "android_set_system_bars",
    ] {
        assert!(command(name)
            .split('{')
            .next()
            .unwrap()
            .contains("Result<(), String>"));
    }
}

