import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseReleaseVersion } from "../src/shared/ReleaseVersion.mjs";
import {
  cargoLockVersionPattern,
  nativeReleaseVersions,
  readReleaseState,
  workspaceReleasePackages,
} from "./release-version-files.mjs";

/** Prepare reviewable local files only. This function never creates a tag or publishes. */
export function setReleaseVersion(root, value, { dryRun = false, env = process.env } = {}) {
  const release = parseReleaseVersion(value);
  if (!release) throw new Error("Specify x.y.z, x.y.z.rcN or x.y.z.postN without a v prefix");
  const state = readReleaseState(root);
  const native = nativeReleaseVersions(release, env);
  const packages = workspaceReleasePackages(root);
  const updates = new Map();
  const serialize = (value) => JSON.stringify(value, null, 2) + "\n";
  updates.set(
    "package.json",
    serialize({ ...state.metadata, version: release.semver, releaseVersion: release.canonical })
  );
  updates.set(
    "src-tauri/tauri.conf.json",
    serialize({
      ...state.tauri,
      version: release.semver,
      bundle: {
        ...state.tauri.bundle,
        android: { ...state.tauri.bundle?.android, versionCode: native.android },
      },
    })
  );
  for (const member of packages)
    updates.set(
      member.relative,
      member.source.replace(
        /(\[package\][\s\S]*?^version\s*=\s*")[^"]+(".*$)/m,
        `$1${release.semver}$2`
      )
    );
  const lockPath = path.join(root, "Cargo.lock");
  if (fs.existsSync(lockPath)) {
    let lock = fs.readFileSync(lockPath, "utf8");
    for (const member of packages) {
      const pattern = cargoLockVersionPattern(member.name);
      if (!pattern.test(lock)) throw new Error(`Could not find ${member.name} in Cargo.lock`);
      lock = lock.replace(pattern, (_match, prefix, suffix) => prefix + release.semver + suffix);
    }
    updates.set("Cargo.lock", lock);
  }
  updates.set(
    "src-tauri/packages/windows/release-version.nsh",
    `; Generated by scripts/set-release-version.mjs.\n!define BAAS_RELEASE_VERSION "${release.canonical}"\n!define BAAS_PLATFORM_VERSION "${native.windows}"\n`
  );
  const macConfigPath = "src-tauri/tauri.macos.conf.json";
  const macConfig = JSON.parse(fs.readFileSync(path.join(root, macConfigPath), "utf8"));
  macConfig.bundle ??= {};
  macConfig.bundle.macOS ??= {};
  Object.assign(macConfig.bundle.macOS, {
    bundleVersion: native.mac,
    infoPlist: "packages/macos/release-version.plist",
  });
  updates.set(macConfigPath, serialize(macConfig));
  updates.set(
    "src-tauri/packages/macos/release-version.plist",
    `<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n<plist version="1.0"><dict>\n<key>CFBundleShortVersionString</key><string>${release.base}</string>\n<key>CFBundleVersion</key><string>${native.mac}</string>\n<key>BAASReleaseVersion</key><string>${release.canonical}</string>\n</dict></plist>\n`
  );
  if (!dryRun)
    for (const [relative, text] of updates) {
      const target = path.join(root, relative);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target + ".tmp", text);
      fs.renameSync(target + ".tmp", target);
    }
  return { ...release, native, files: [...updates.keys()], dryRun };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (
      args.some((arg) => arg.startsWith("--") && arg !== "--dry-run") ||
      args.filter((arg) => !arg.startsWith("--")).length !== 1
    )
      throw new Error(
        "Usage: node scripts/set-release-version.mjs <x.y.z[.rcN|.postN]> [--dry-run]"
      );
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
    console.log(
      JSON.stringify(
        setReleaseVersion(
          root,
          args.find((arg) => !arg.startsWith("--")),
          { dryRun: args.includes("--dry-run") }
        ),
        null,
        2
      )
    );
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
