import importlib.util
import os
import sys
import tempfile
import types
import unittest
from pathlib import Path
from unittest.mock import Mock, patch

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
MODULES = ROOT / "src-tauri/gen/android/app/src/main/python/android_backend"


def load(name):
    spec = importlib.util.spec_from_file_location(name, MODULES / (name + ".py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class NativeCaptureTest(unittest.TestCase):
    def test_native_frontend_bridge_commands_are_allowed(self):
        try:
            import tomllib
        except ModuleNotFoundError:
            import tomli as tomllib
        permissions = tomllib.loads((ROOT / "src-tauri/permissions/autogenerated/commands/mobile-commands.toml").read_text())
        allowed = permissions["permission"][0]["commands"]["allow"]
        for command in ("android_game_native_preview", "android_open_shizuku", "android_set_system_bars"):
            with self.subTest(command=command):
                self.assertIn(command, allowed)

    def test_native_selection_overrides_legacy_adb_and_is_idempotent(self):
        bootstrap = load("bootstrap")
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "service/conf").mkdir(parents=True)
            manager = root / "service/conf/manager.py"
            manager.write_text(
                "import os, copy\nclass Manager:\n"
                "    @staticmethod\n    def normalize(data):\n"
                "        normalized = copy.deepcopy(data)\n"
                "        normalized['control_method'] = 'adb'\n"
                "        normalized['screenshot_method'] = 'adb'\n"
                "        return normalized\n", encoding="utf-8")
            injection = root / "service/injection.py"
            injection.write_text(
                "import os\ndef _scrcpy_virtual_display_enabled() -> bool:\n    return True\n",
                encoding="utf-8")
            bootstrap._patch_android_native_capture_runtime(root)
            first = manager.read_text()
            bootstrap._patch_android_native_capture_runtime(root)
            self.assertEqual(first, manager.read_text())
            namespace = {}
            exec(first, namespace)
            with patch.dict(os.environ, {"BAAS_ANDROID_NATIVE_CAPTURE": "1"}):
                normalized = namespace["Manager"].normalize({"server": "JP", "custom": 7})
                self.assertEqual(normalized["screenshot_method"], "android_local")
                self.assertEqual(normalized["control_method"], "android_local")
                self.assertEqual(normalized["adbPort"], "7912")
                self.assertEqual(normalized["custom"], 7)
                exec(injection.read_text(), namespace)
                self.assertFalse(namespace["_scrcpy_virtual_display_enabled"]())
            self.assertIn("from android_backend.native_device import", (root / "service/android_local_device.py").read_text())

    def test_control_uses_local_rpc_and_preserves_duration(self):
        native = load("native_device")
        conn = type("Connection", (), {"serial": "127.0.0.1:7912"})()
        control = native.AndroidLocalControl(conn)
        with patch.object(native, "_rpc", return_value=True) as rpc:
            self.assertTrue(control.click(10, 20))
            rpc.assert_called_with("click", [10, 20])
            control.swipe(10, 20, 30, 40, 0.5)
            rpc.assert_called_with("swipe", [10, 20, 30, 40, 100])
            control.long_click(10, 20, 0.8)
            rpc.assert_called_with("swipe", [10, 20, 10, 20, 160])


class GameResourceUpdateTest(unittest.TestCase):
    def setUp(self):
        self.guard = load("game_update_dialog")
        self.environment = patch.dict(os.environ, {
            "BAAS_ANDROID": "1", "BAAS_ANDROID_NATIVE_CAPTURE": "1",
        })
        self.environment.start()
        self.addCleanup(self.environment.stop)

    @staticmethod
    def notice_image():
        # Synthetic UI geometry only; no private screenshot is stored in the repo.
        image = np.full((720, 1280, 3), 80, dtype=np.uint8)
        image[136:581, 359:919] = (239, 239, 239)
        image[469:540, 394:635] = (237, 230, 207)
        image[469:540, 647:887] = (253, 219, 115)
        return image

    def baas(self, text=None):
        return types.SimpleNamespace(
            server="CN", latest_img_array=self.notice_image(), logger=Mock(),
            click=Mock(), signal_stop=Mock(),
            ocr=types.SimpleNamespace(get_region_res=Mock(side_effect=text or [
                "需要下载4.94 MB的更新包。", "是否继续？（推荐在Wi-Fi环境下载）",
                "通知", "取消", "确认",
            ])),
        )

    def test_layout_rejects_blank_screen_and_missing_buttons(self):
        image = self.notice_image()
        self.assertTrue(self.guard.has_download_layout(image))
        self.assertFalse(self.guard.has_download_layout(np.full_like(image, 239)))
        image[469:540, 647:887] = (239, 239, 239)
        self.assertFalse(self.guard.has_download_layout(image))

    def test_real_device_notice_layout_when_external_fixture_is_supplied(self):
        fixture = os.getenv("BAAS_ANDROID_UPDATE_FIXTURE")
        if not fixture:
            self.skipTest("Set BAAS_ANDROID_UPDATE_FIXTURE to a local device screenshot")
        from PIL import Image
        image = np.asarray(Image.open(fixture).convert("RGB"))[:, :, ::-1].copy()
        self.assertTrue(self.guard.has_download_layout(image))
        baas = self.baas()
        baas.latest_img_array = image
        self.assertTrue(self.guard.handle_resource_update(baas))
        baas.click.assert_called_once_with(768, 504, wait_over=True)

    def test_text_requires_download_size_network_notice_and_exact_buttons(self):
        valid = ["通知", "需要下载4.94 MB的更新包。", "是否继续？（推荐在Wi-Fi环境下载）", "取消", "确认"]
        self.assertTrue(self.guard.matches_download_text(*valid))
        for size in ("128KB", "0.25GB", "4.94MiB"):
            changed = valid.copy()
            changed[1] = "需要下载" + size + "的更新包。"
            self.assertTrue(self.guard.matches_download_text(*changed))
        for index, replacement in (
            (0, "购买确认"), (1, "消耗100青辉石购买体力"), (1, "扫荡次数3次"),
            (1, "需要下载0 MB的更新包。"), (1, "需要下载4.94的更新包。"),
            (2, "是否继续购买？"), (3, "确认"), (4, "取消"),
        ):
            changed = valid.copy()
            changed[index] = replacement
            with self.subTest(replacement=replacement):
                self.assertFalse(self.guard.matches_download_text(*changed))

    def test_normal_frames_and_other_servers_do_not_call_ocr(self):
        baas = self.baas()
        baas.latest_img_array[:] = 0
        self.assertFalse(self.guard.handle_resource_update(baas))
        baas.ocr.get_region_res.assert_not_called()
        baas.latest_img_array = self.notice_image()
        baas.server = "JP"
        self.assertFalse(self.guard.handle_resource_update(baas))
        baas.ocr.get_region_res.assert_not_called()

    def test_ordinary_notice_never_authorizes_update_click(self):
        baas = self.baas(["消耗100青辉石购买体力", "是否继续购买？"])
        self.assertFalse(self.guard.handle_resource_update(baas))
        baas.click.assert_not_called()
        baas.signal_stop.assert_not_called()

    def test_verified_notice_is_confirmed_once_then_consumed(self):
        baas = self.baas()
        text = list(baas.ocr.get_region_res.side_effect)
        baas.ocr.get_region_res.side_effect = text * 2
        with patch.object(self.guard.time, "monotonic", side_effect=[100, 101]), \
             patch.object(self.guard.time, "sleep"):
            self.assertTrue(self.guard.handle_resource_update(baas))
            self.assertTrue(self.guard.handle_resource_update(baas))
        baas.click.assert_called_once_with(768, 504, wait_over=True)
        self.assertEqual(baas.last_click_name, "android_game_resource_update")

    def test_unverified_update_or_ocr_failure_stops_before_generic_close(self):
        for text in (
            ["需要下载4.94的更新包。", "是否继续？", "通知", "取消", "确认"],
            ["需要下载4.94MB的更新包。", "是否继续？（推荐在Wi-Fi环境下载）", "通知", "确认", "取消"],
        ):
            baas = self.baas(text)
            with self.assertRaises(self.guard.ManualGameUpdateRequired):
                self.guard.handle_resource_update(baas)
            baas.signal_stop.assert_called_once()
            baas.click.assert_not_called()
        baas = self.baas()
        baas.ocr.get_region_res.side_effect = RuntimeError("OCR unavailable")
        with self.assertRaises(self.guard.ManualGameUpdateRequired):
            self.guard.handle_resource_update(baas)
        baas.signal_stop.assert_called_once()
        baas.click.assert_not_called()

    def test_persistent_confirmed_notice_stops_instead_of_hanging(self):
        baas = self.baas()
        baas._android_resource_update_confirmation = ("需要下载4.94mb的更新包。", 100)
        with patch.object(self.guard.time, "monotonic", return_value=131), \
             self.assertRaises(self.guard.ManualGameUpdateRequired):
            self.guard.handle_resource_update(baas)
        baas.signal_stop.assert_called_once()
        baas.click.assert_not_called()

    def test_dismissed_notice_does_not_block_a_later_update_of_the_same_size(self):
        baas = self.baas()
        baas._android_resource_update_confirmation = ("需要下载4.94mb的更新包。", 100)
        baas.latest_img_array[:] = 0
        self.assertFalse(self.guard.handle_resource_update(baas))
        baas.latest_img_array = self.notice_image()
        with patch.object(self.guard.time, "monotonic", return_value=200):
            self.assertTrue(self.guard.handle_resource_update(baas))
        baas.click.assert_called_once_with(768, 504, wait_over=True)

    def test_bootstrap_hook_consumes_update_before_old_image_reactions(self):
        bootstrap = load("bootstrap")
        calls = []
        adapter = types.ModuleType("android_backend.game_update_dialog")
        adapter.handle_resource_update = Mock(side_effect=[True, False])
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            picture = root / "core/picture.py"
            picture.parent.mkdir()
            picture.write_text(
                "import time\ndef co_detect(self):\n"
                "    fail_cnt = 0\n    feature_last_appear_time = 0\n"
                "    while self.flag_run:\n        current_time = time.time()\n"
                "        self.update_screenshot_array()\n"
                "        # loading check\n        self.old_close()\n        return 'generic'\n",
                encoding="utf-8")
            bootstrap._patch_android_game_resource_update(root)
            patched = picture.read_text(encoding="utf-8")
            bootstrap._patch_android_game_resource_update(root)
            self.assertEqual(patched, picture.read_text(encoding="utf-8"))
            with patch.dict(sys.modules, {"android_backend.game_update_dialog": adapter}):
                namespace = {}
                exec(patched, namespace)
            baas = types.SimpleNamespace(flag_run=True,
                update_screenshot_array=lambda: calls.append("frame"),
                old_close=lambda: calls.append("generic"))
            self.assertEqual(namespace["co_detect"](baas), "generic")
            self.assertEqual(calls, ["frame", "frame", "generic"])
            self.assertEqual(adapter.handle_resource_update.call_count, 2)


